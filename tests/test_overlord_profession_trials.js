const assert = require('node:assert/strict');
const { createTrialWorld, pilgrim, glory, finishRoute, abort, H, Service } = require('./helpers/secondProfessionHarness');

(async () => {
    const c = await createTrialWorld('overlord', 171001, [{ id: 171002, classId: 50, race: 3, level: 39 }]);
    try {
        await pilgrim(c); await glory(c);
        assert.equal(await c.event(232, 'start', 7565), false);
        await c.level(39); await c.click(232, 'start', 7565);
        assert.equal(await c.event(232, 'handin', 7565), false);
        await c.kill(588, 11); assert.equal(await c.amount(3403), 10, 'C4 permits Timak skull collection before Hatos');
        for (const npc of [7642, 7641, 7568, 7567, 7566, 7515]) await c.click(232, 'handin', npc);
        assert.equal(await c.event(232, 'handin', 7558), false);
        await Service.giveItem(c.session, 57, 999);
        assert.equal(await c.event(232, 'handin', 7558), false); assert.equal(await c.amount(57), 999);
        await Service.giveItem(c.session, 57, 1); await c.click(232, 'handin', 7558);
        assert.equal(await c.amount(57), 0);
        await Service.giveItem(c.session, 1341, 999);
        assert.equal(await c.event(232, 'handin', 7567), false); assert.equal(await c.amount(1341), 999);
        await Service.giveItem(c.session, 1341, 1); await c.click(232, 'handin', 7567);
        assert.equal(await c.amount(1341), 0); assert.equal(await c.event(232, 'handin', 7558), false);
        await c.kill(233, 10); assert.equal(await c.amount(3408), 10); assert.equal(await c.amount(3407), 0);
        await c.reopen(); await c.kill(233, 11);
        assert.equal(await c.amount(3408), 10); assert.equal(await c.amount(3407), 10);
        await c.click(232, 'handin', 7641);
        await c.click(232, 'handin', 7564); await c.click(232, 'handin', 7510); await c.click(232, 'handin', 7568);
        await c.kill(564, 1, .9); assert.equal(await c.amount(3410), 0);
        await c.kill(564, 21); assert.equal(await c.amount(3410), 20); await c.click(232, 'handin', 7642);
        await c.kill(269, 1, .4); assert.equal(await c.amount(3398), 0);
        await c.kill(270, 21); assert.equal(await c.amount(3398), 20);
        await c.click(232, 'handin', 7515); await c.click(232, 'handin', 7566);
        await c.reopen(); await c.click(232, 'handin', 7565);
        assert.equal(c.state(232).getInt('phase'), 2); assert.equal(await c.amount(3412), 1);
        await c.kill(778); assert.equal(await c.amount(3414), 0, 'Ragna hunt requires Martankus charm');
        await c.click(232, 'handin', 7649); await c.kill(779, 2);
        assert.equal(await c.amount(3415), 1); assert.equal(await c.event(232, 'handin', 7649), false);
        await c.kill(778, 2); assert.equal(await c.amount(3414), 1);
        await c.click(232, 'handin', 7649); await c.click(232, 'summon', 7649);
        await c.click(232, 'summon', 7649); assert.equal(H.personalSpawns(c.state(232), 7643).length, 1);
        const orc = H.personalSpawns(c.state(232), 7643)[0], other = await c.world.session(171002);
        await c.world.event(other, 232, 'start', 7565);
        other.activeNpcTalk = { selfId: 7643, objectId: orc.fetchId() };
        assert.equal(await Service.onEvent(other, { questId: 232, name: 'story' }), false);
        H.clearSpawns(c.state(232)); await c.reopen(); await c.click(232, 'summon', 7649);
        assert.equal(H.personalSpawns(c.state(232), 7643).length, 1);
        await c.personalEvent(232, 'story', 7643); await c.personalEvent(232, 'legacy', 7643);
        await c.click(232, 'handin', 7565);
        assert.equal(H.personalSpawns(c.state(232), 7643).length, 0);
        assert.equal(await c.amount(3390), 1); assert.equal(await c.amount(7562), 24);
        const row = await c.world.character(c.id);
        assert.equal(row.exp, 262244); assert.equal(row.sp, 34750);
        assert.equal(await c.event(232, 'handin', 7565), false); assert.deepEqual(await c.world.character(c.id), row);
        const resumedOther = await c.world.session(171002);
        await c.world.kill(resumedOther, 588);
        await Service.giveItem(resumedOther, 1341, 42);
        await Service.giveItem(resumedOther, 57, 123);
        await abort(resumedOther, 232);
        assert.equal(await c.world.amount(171002, 3403), 0);
        assert.equal(await c.world.amount(171002, 3391), 0);
        assert.equal(await c.world.amount(171002, 1341), 42);
        assert.equal(await c.world.amount(171002, 57), 123);
        assert.equal(await c.world.event(resumedOther, 232, 'start', 7565), true);
        await finishRoute(c, 51, [[1003, 2], [1004, 1], [1250, 1], [239, 2]]);
        console.log('Overlord: full C4 Shaman route, five independent tribes, resource payments, First Orc recovery and persisted skills passed');
    } finally { await c.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
