const assert = require('node:assert/strict');
const { createTrialWorld, pilgrim, glory, finishRoute, abort, H, Service } = require('./helpers/shamanProfessionHarness');

(async () => {
    const c = await createTrialWorld('warcryer', 170001, [{ id: 170002, classId: 50, race: 3, level: 39 }]);
    try {
        await pilgrim(c, { book: true, keep: true });
        await glory(c);
        assert.equal(await c.event(233, 'start', 7510), false);
        await c.level(39); await c.click(233, 'start', 7510);
        assert.equal(await c.event(233, 'handin', 7649), false);
        const other = await c.world.session(170002);
        await c.world.event(other, 233, 'start', 7510);
        await c.world.event(other, 233, 'handin', 7515);
        for (const npc of [7507, 7515, 7682, 7630, 7030, 7436]) await c.click(233, 'handin', npc);
        await c.kill(601); assert.equal(await c.amount(2881), 0, 'Tamlin hunt requires the vendetta totem');
        await c.kill(5108);
        assert.equal(H.personalSpawns(c.state(233), 158).length, 5);
        await c.kill(5108); assert.equal(await c.amount(2896), 1);
        assert.equal(H.personalSpawns(c.state(233), 158).length, 5);
        const foreign = H.personalSpawns(c.state(233), 158)[0];
        await Service.onKill(other, foreign);
        assert.equal(await c.world.amount(170002, 2897), 0, 'foreign quest Medusas cannot advance another player');
        H.clearSpawns(c.state(233)); await c.reopen();
        await c.click(233, 'recover', 7515); await c.click(233, 'recover', 7515);
        assert.equal(H.personalSpawns(c.state(233), 158).length, 5, 'recovery after restart does not duplicate the encounter');
        await c.ownedKill(233, 158);
        for (const i of [2897, 2898, 2899, 2900]) assert.equal(await c.amount(i), 1);
        assert.equal(H.personalSpawns(c.state(233), 158).length, 0);
        await c.click(233, 'handin', 7515);
        await c.kill(581, 1, .5); assert.equal(await c.amount(2889), 0);
        await c.kill(582);
        for (const i of [2889, 2890, 2891, 2892, 2893]) assert.equal(await c.amount(i), 1, 'C4 gives all missing Tonar bones on the successful roll');
        await c.click(233, 'handin', 7682);
        await c.kill(89, 1, .71); assert.equal(await c.amount(2909), 0);
        await c.kill(90, 1, .70); assert.equal(await c.amount(2909), 1); assert.equal(await c.amount(2908), 1);
        await c.kill(89, 1, .41); assert.equal(await c.amount(2907), 0);
        await c.kill(90, 1, .40); assert.equal(await c.amount(2907), 1); assert.equal(await c.amount(2906), 1);
        await c.kill(89, 1, .11); assert.equal(await c.amount(2905), 0);
        await c.kill(90, 1, .10); await c.kill(89, 2);
        for (const i of [2905, 2906, 2907, 2908, 2909]) assert.equal(await c.amount(i), 1);
        await c.click(233, 'handin', 7507);
        await c.reopen();
        assert.equal(c.state(233).getInt('Manakia'), 7); assert.equal(c.state(233).getInt('Racoy'), 11);
        assert.equal(await c.event(233, 'handin', 7630), false);
        await c.kill(215, 3); await c.kill(214, 3); await c.kill(213, 11);
        for (const i of [2884, 2885, 2886]) assert.equal(await c.amount(i), 10);
        await c.click(233, 'handin', 7630);
        assert.equal(c.cond(233), 2);
        await c.click(233, 'handin', 7510);
        await c.kill(601, 1, .5); assert.equal(await c.amount(2881), 0);
        await c.kill(602, 14); assert.equal(await c.amount(2881), 13);
        await c.reopen(); await c.click(233, 'handin', 7510);
        assert.equal(await c.event(233, 'handin', 7510), false);
        for (const i of [2882, 2911, 2912, 2913, 2914]) assert.equal(await c.amount(i), 1);
        await c.click(233, 'handin', 7649);
        assert.equal(await c.amount(2879), 1); assert.equal(await c.amount(7562), 24);
        const row = await c.world.character(c.id);
        assert.equal(row.exp, 232772); assert.equal(row.sp, 36000);
        assert.equal(await c.event(233, 'handin', 7649), false);
        assert.deepEqual(await c.world.character(c.id), row);
        const resumedOther = await c.world.session(170002);
        await c.world.kill(resumedOther, 5108);
        const otherState = c.world.state(resumedOther, 233);
        assert.equal(H.personalSpawns(otherState, 158).length, 5);
        c.state(215).addRadar(90, 80, 70);
        await abort(resumedOther, 233);
        assert.equal(H.personalSpawns(otherState, 158).length, 0);
        assert.equal(await c.world.amount(170002, 2896), 0);
        assert(c.session.questWaypoints.size > 0, 'another player and quest retain their radar');
        assert.equal(await c.world.event(resumedOther, 233, 'start', 7510), true);
        await finishRoute(c, 52, [[1006, 2], [1009, 3], [1252, 1], [239, 2]]);
        console.log('Warcryer: full C4 Shaman route, parallel trials, owned encounter recovery, rewards and persisted skills passed');
    } finally { await c.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
