'use strict';
const assert = require('node:assert/strict');
require('./helpers/databaseIsolation');
require('../src/Global');
invoke('GameServer/DataCache').init();
const { BoardIndex, BUY, SELL, compareLines, rowOf } = require('../src/GameServer/AfkTrade/BoardIndex');
const Price = require('../src/GameServer/Bot/Economy/PriceDecision');
const board = new BoardIndex();
const record = (id, custody, price, count = 1) => ({ id, ownerId: id + 1000, storeType: BUY,
    kind: custody ? 'buy_ad' : 'shop', custodyPolicy: custody, revision: 1, town: 'Giran',
    lines: [{ id: id * 10, lineId: id * 10, selfId: 1464, count, price, enchant: 0 }] });
for (let i = 1; i <= 200; i++) board.put(record(i, 1, 10000 + i));
for (let i = 1; i <= 6; i++) board.put(record(300 + i, 0, 500 + i));
const quotes = () => Price.productionBids(board, 1464);
assert.equal(quotes().length, 2 * Price.QUOTE_DEPTH);
assert.equal(quotes().filter(line => line.custodyPolicy !== 1).length, Price.QUOTE_DEPTH);
assert.deepEqual(quotes(), [...quotes()].sort(compareLines), 'the union retains native price and tie order');
assert(quotes().some(line => line.recordId === 306), 'the best backed bid survives two hundred higher ads');
assert(!quotes().some(line => line.recordId === 301), 'backed inspection stays bounded too');
const originalList = board.list;
let reads = 0;
board.list = (...args) => new Proxy(originalList.apply(board, args), { get(target, key) {
    if (/^\d+$/.test(String(key))) reads++;
    return Reflect.get(target, key);
} });
quotes();
assert.equal(reads, Price.QUOTE_DEPTH, 'finding the backed head never scans the conditional tail');
board.list = originalList;
board.put(record(306, 0, 30000));
assert.equal(quotes().filter(line => line.recordId === 306).length, 1, 'a bid present in both heads is not duplicated');
assert.equal(quotes()[0].recordId, 306, 'reprice moves the same source in both books');
board.put(record(306, 1, 40000));
assert(!board.backedBids(1464).some(line => line.recordId === 306), 'changing custody removes old backed authority');
board.put(record(305, 0, 500, 0));
assert(!board.backedBids(1464).some(line => line.recordId === 305), 'zero stock leaves the backed index');
board.remove(304);
assert(!board.backedBids(1464).some(line => line.recordId === 304), 'closed shops leave the backed index');
const mirror = new BoardIndex(), follower = mirror.follower(), source = record(900, 0, 400);
follower.put(source.id, rowOf(source));
assert.equal(mirror.backedBids(1464)[0].lineId, 9000);
follower.put(source.id, rowOf({ ...source, storeType: SELL }));
assert.equal(mirror.backedBids(1464).length, 0, 'replacement on another side retires the old bid');
follower.put(source.id, rowOf(source));
follower.remove(source.id);
assert.equal(mirror.backedBids(1464).length, 0);
follower.put(source.id, rowOf(source));
follower.reset();
assert.equal(mirror.backedBids(1464).length, 0, 'table resync retains no stale backed references');
assert.equal(Price.productionBids(null, 1464).length, 0);
board.clear();
assert.equal(board.backedBuys.size, 0);
assert.equal(quotes().length, 0);
console.log('PASS bounded production bid union, indexed lifecycle, deduplication and worker table resync');
