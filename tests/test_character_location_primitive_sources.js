index.put(actor); index.setSource(1, 'state', original);
strict.setSource(1, 'state', rawObject, { indexed: false });
assert.equal(index.get(1), actor);
assert.equal(index.getSource(1, 'state'), original);
assert.deepEqual(index.near(point, 1), [actor]);
assert.deepEqual(index.nearSources(point, 1, { view: 'state', kind: 'cold' }), [original]);
assert.equal(strict.getSource(1, 'state'), rawObject);
assert.deepEqual([...strict.sourceValues('state')], [rawObject]);
assert.equal(reads, 0);
for (const value of [...values, null, undefined]) {
    const record = { id: 1, source: value, get phase() { tagReads++; return 'hot'; }, get loc() { reads++; return point; } };
    assert.throws(() => strict.setSource(1, 'state', record, { indexed: false }), RangeError);
    assert.throws(() => index.setSource(1, 'actor', record, { indexed: false }), RangeError);
    assert.throws(() => index.setSource(1, 'state', record, { indexed: true }), RangeError);
    assert.equal(strict.getSource(1, 'state'), rawObject);
    assert.equal(index.get(1), actor);
    assert.equal(index.getSource(1, 'state'), original);
    assert.equal(reads, 0, 'strict source validation runs before an otherwise valid point getter or eviction');
    assert.equal(tagReads, 0, 'strict source validation also precedes membership evaluation');
}
const cache = new Cache();
for (const [id, value] of values.entries()) {
    assert.equal(cache.set(id, value), cache);
    assert.equal(cache.has(id), true);
    assert(Object.is(cache.get(id), value));
}
cache.clear();
console.log('PASS actual strict/default/actor/indexed primitive rejection, raw object and successful Cache primitive positives');

