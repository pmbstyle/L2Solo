'use strict';

const assert = require('node:assert/strict');
const Index = require('../src/GameServer/World/CharacterLocationIndex');
const Cache = require('../src/GameServer/Bot/Population/LifeStateCache');
const point = { locX: 0, locY: 0, locZ: 0 };
const values = [0, -0, NaN, Infinity, -Infinity, 42, 0n, 17n, '', 'state', false, true, Symbol('state')];
const index = new Index({ legacyStateCache: true }), strict = new Index();
const actor = { id: 1, source: {}, phase: 'hot', loc: point, spotId: 'one' };
const original = { id: 1, source: {}, phase: 'cold', loc: point, spotId: 'one' };
let reads = 0, tagReads = 0;
