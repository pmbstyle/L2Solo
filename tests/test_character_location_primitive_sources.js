assert.equal(reads, 0, 'enabling a raw primitive rejects before its valid point getter');
assert.equal(tagReads, tagsBeforeEnable, 'enabling a raw primitive rejects before membership evaluation');
assert.equal(index.getSource(1, 'state'), primitive);
assert.equal(index.cells.get('0_0').actor.all, actorCell);
assert.equal(index.spots.get('one').actor, actorSpot);
assert.equal(index.updateSource(1, 'state', 0), true);
assert.equal(index.updateSource(1, 'state', original.source), false);
assert.equal(index.removeSource(1, 'state', original.source), false);
