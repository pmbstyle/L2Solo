    assert(Object.is(index.records.get(1).state.source, value));
    assert.equal(index.updateSource(1, 'state', value), true);
    assert.throws(() => index.updateSource(1, 'state', value, { indexed: true }), RangeError);
    assert.throws(() => index.setSource(1, 'state', record, { indexed: true }), RangeError);
    assert.equal(index.getSource(1, 'state'), record);
    assert.equal(reads, 0);
    assert.equal(index.removeSource(1, 'state', value), true);
    assert.equal(index.getSource(1, 'state'), null);
